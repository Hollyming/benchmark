from __future__ import annotations

from pathlib import Path
from typing import Dict, List

from ultra_long_benchmark.models import MemoryChallengeQuery, PersonaTimeline, Trajectory, model_validate
from ultra_long_benchmark.shared.io import read_jsonl, write_json, write_text


def package_release(timelines_path: Path, trajectories_path: Path, queries_path: Path, output_dir: Path) -> Dict[str, object]:
    timelines = [model_validate(PersonaTimeline, row) for row in read_jsonl(timelines_path)]
    trajectories = [model_validate(Trajectory, row) for row in read_jsonl(trajectories_path)]
    queries = [model_validate(MemoryChallengeQuery, row) for row in read_jsonl(queries_path)]
    splits = make_splits([q.query_id for q in queries])
    manifest = {
        "dataset_name": "ultra_long_trajectory_benchmark_synthetic_smoke",
        "version": "0.1.0",
        "licenses": ["synthetic"],
        "counts": {"timelines": len(timelines), "trajectories": len(trajectories), "queries": len(queries)},
        "splits": {key: len(value) for key, value in splits.items()},
        "provenance": "Generated by deterministic offline smoke pipelines.",
    }
    write_json(output_dir / "release_manifest.json", manifest)
    write_json(output_dir / "splits.json", splits)
    write_text(output_dir / "DATASET_CARD.md", dataset_card(manifest))
    write_text(output_dir / "BENCHMARK_CARD.md", benchmark_card())
    return manifest


def make_splits(ids: List[str]) -> Dict[str, List[str]]:
    ordered = sorted(ids)
    if len(ordered) <= 3:
        return {"train": ordered[:1], "dev": ordered[1:2], "test": ordered[2:]}
    train_cut = max(1, int(len(ordered) * 0.6))
    dev_cut = max(train_cut + 1, int(len(ordered) * 0.8))
    return {"train": ordered[:train_cut], "dev": ordered[train_cut:dev_cut], "test": ordered[dev_cut:]}


def dataset_card(manifest: Dict[str, object]) -> str:
    return f"""# Dataset Card

Name: {manifest['dataset_name']}

Version: {manifest['version']}

This smoke release contains deterministic synthetic timelines, trajectories, and memory challenge queries. It is intended for pipeline validation, schema testing, and benchmark-method development, not for claims about production model behavior.

Primary risks: synthetic bias, privacy leakage in future real-data ingestion, annotation ambiguity, and benchmark overfitting.
"""


def benchmark_card() -> str:
    return """# Benchmark Card

The benchmark evaluates memory-enabled agents over long-horizon trajectories. Capabilities include episodic recall, temporal reasoning, preference drift, contradiction resolution, provenance-aware answering, long-horizon planning, privacy-sensitive refusal, and abstention.

Recommended reporting: per-capability accuracy, evidence citation quality, privacy refusal rate, abstention calibration, latency, storage budget, and performance as trajectory length grows.
"""

